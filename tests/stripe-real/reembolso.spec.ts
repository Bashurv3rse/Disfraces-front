import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import type Stripe from "../../../backend/node_modules/stripe";
import { test, expect } from "../e2e/fixtures/catalogo";
import { CatalogoPage } from "../e2e/pages/CatalogoPage";
import { CarritoPage } from "../e2e/pages/CarritoPage";
import { AdminPage } from "../e2e/pages/AdminPage";
import { GarantiasPage } from "../e2e/pages/GarantiasPage";
import { MisAlquileresPage } from "../e2e/pages/MisAlquileresPage";
import { iniciarConsumidor } from "./consumidor";

const coexistencia = process.env.STRIPE_COEXISTENCIA === '1';
test(coexistencia ? "PI-CEX-STRIPE-01: coexistencia funcional con consumidor independiente en Stripe TEST" : "TC-E2E-REE-01: pago y reembolso de garantía contra Stripe real en modo prueba", async ({ page, browser, request, catalogo }) => {
  const requireBackend = createRequire(new URL("../../../backend/package.json", import.meta.url));
  const { parse } = requireBackend("dotenv") as typeof import("../../../backend/node_modules/dotenv");
  const env = parse(readFileSync(new URL("../../../backend/.env.test", import.meta.url)));
  expect(env.NODE_ENV).toBe("test");
  expect(new URL(env.DATABASE_URL).pathname).toBe("/disfraz_test_db");
  expect(env.STRIPE_SECRET_KEY?.startsWith("sk_test_")).toBe(true);
  const ClienteStripe = requireBackend("stripe") as typeof Stripe;
  const stripe = new ClienteStripe(env.STRIPE_SECRET_KEY, { maxNetworkRetries: 1, timeout: 20_000 });
  const modo = await request.get("http://localhost:3000/__e2e/stripe-real");
  expect(modo.status(), "Inicia npm run start:test:stripe-real; no sirve el servidor simulado").toBe(200);
  expect(await modo.json()).toEqual({ modo: "stripe-real-test", base: "disfraz_test_db", livemode: false });
  expect((await stripe.balance.retrieve()).livemode).toBe(false);
  const evidencia: Record<string, unknown> = { caso: coexistencia ? "PI-CEX-STRIPE-01" : "TC-E2E-REE-01", fecha: new Date().toISOString(), estado: "EN_CURSO", livemode: false, etapa: "inicio" };
  const directorio = new URL(coexistencia ? "../../../tests/auditoria/coexistencia-stripe/" : "../../../tests/auditoria/stripe-real/", import.meta.url);
  mkdirSync(directorio, { recursive: true });
  let sesionId: string | undefined;
  let adminId: string | undefined;
  const contextoAdmin = await browser.newContext();
  let consumidor: Awaited<ReturnType<typeof iniciarConsumidor>> | undefined;
  try {
    if (coexistencia) {
      consumidor = await iniciarConsumidor();
      expect(consumidor.listo.cuentaId).toBe((await stripe.accounts.retrieve(null)).id);
      evidencia.consumidorInicio = consumidor.listo;
    }
    const inicioAplicacion = Date.now();
    evidencia.inicioAplicacion = inicioAplicacion;
    const disfraz = await catalogo.crear("reembolso Stripe real TEST");
    const ui = new CatalogoPage(page);
    await ui.iniciarSesion(catalogo.email, catalogo.password);
    await ui.buscar(catalogo.prefijo);
    await ui.agregar(disfraz.nombre);
    const carrito = new CarritoPage(page);
    const inicio = new Date(Date.now() + 7 * 86_400_000);
    const fin = new Date(+inicio + 3 * 86_400_000);
    const cotizada = await carrito.fechas(inicio.toISOString().slice(0, 10), fin.toISOString().slice(0, 10));
    expect(await cotizada.json()).toMatchObject({ totalAlquiler: 120, garantia: 30, totalAPagar: 150 });
    const checkout = page.waitForResponse(res => res.url().endsWith("/api/pagos/crear-sesion") && res.request().method() === "POST");
    await carrito.dialogo.getByRole("button", { name: "Pagar · S/ 150.00", exact: true }).click();
    expect((await checkout).status()).toBe(201);
    await expect(page).toHaveURL(/^https:\/\/checkout\.stripe\.com\//, { timeout: 45_000 });
    sesionId = page.url().match(/cs_test_[a-zA-Z0-9]+/)?.[0];
    expect(sesionId).toBeDefined();
    evidencia.sessionId = sesionId;
    evidencia.etapa = "checkout_creado";
    writeFileSync(new URL("resultado.json", directorio), JSON.stringify(evidencia, null, 2));
    // Solo tarjeta pública de pruebas de Stripe, nunca datos bancarios del usuario.
    await page.locator('#cardNumber').waitFor({ state: "visible", timeout: 30_000 });
    await page.locator('#email').fill(catalogo.email);
    await page.locator('#cardNumber').fill("4242424242424242");
    await page.locator('#cardExpiry').fill("12/30");
    await page.locator('#cardCvc').fill("123");
    await page.locator('#billingName').fill("Cliente RTM TEST");
    const pais = page.locator('#billingCountry');
    if (await pais.count()) await pais.selectOption("PE");
    const postal = page.locator('#billingPostalCode');
    if (await postal.isVisible()) await postal.fill("15001");
    await page.locator('button[type="submit"]').click();
    await expect(page).toHaveURL(/localhost:5173\/pago-exitoso\?session_id=/, { timeout: 60_000 });
    await expect(page.getByRole("heading", { name: /¡Pago confirmado!/ })).toBeVisible({ timeout: 30_000 });
    const sesion = await stripe.checkout.sessions.retrieve(sesionId!);
    expect(sesion.livemode).toBe(false);
    expect(sesion.payment_status).toBe("paid");
    expect(sesion.amount_total).toBe(15000);
    const paymentIntentId = typeof sesion.payment_intent === "string" ? sesion.payment_intent : sesion.payment_intent!.id;
    const intent = await stripe.paymentIntents.retrieve(paymentIntentId);
    const chargeId = typeof intent.latest_charge === "string" ? intent.latest_charge : intent.latest_charge!.id;
    const cargo = await stripe.charges.retrieve(chargeId);
    expect(cargo.livemode).toBe(false);
    expect(cargo.payment_method_details?.card?.last4).toBe("4242");
    evidencia.etapa = "pago_confirmado";
    evidencia.paymentIntentId = paymentIntentId;
    evidencia.chargeId = chargeId;
    evidencia.paymentMethodId = cargo.payment_method;
    evidencia.totalCentavos = 15000;
    const alquiler = await catalogo.db.alquiler.findUniqueOrThrow({ where: { stripeSessionId: sesionId } });
    evidencia.alquilerId = alquiler.id;
    await page.getByRole("link", { name: "Ver mis alquileres", exact: true }).click();
    const tarjeta = page.locator(".alquiler-card").filter({ hasText: disfraz.nombre });
    await tarjeta.getByRole("button", { name: "Devolver", exact: true }).click();
    const modal = page.getByRole("dialog", { name: "Reportar estado de devolución", exact: true });
    await modal.getByRole("button", { name: "Buen estado", exact: true }).click();
    const reporte = page.waitForResponse(res => res.url().endsWith("/api/devoluciones") && res.request().method() === "POST");
    await modal.getByRole("button", { name: "Confirmar devolución", exact: true }).click();
    expect((await reporte).status()).toBe(201);
    const devolucion = await catalogo.db.devolucion.findUniqueOrThrow({ where: { alquilerId: alquiler.id } });
    const bcrypt = requireBackend("bcryptjs") as { hash: (valor: string, rondas: number) => Promise<string> };
    const admin = await catalogo.db.usuario.create({ data: { nombre: `${catalogo.prefijo} admin`, email: `admin-${catalogo.email}`, password: await bcrypt.hash(catalogo.password, 10), telefono: "987654321", direccion: "Dirección TEST", rol: "ADMINISTRADOR" } });
    adminId = admin.id;
    const paginaAdmin = await contextoAdmin.newPage();
    await new AdminPage(paginaAdmin).iniciarSesion(admin.email, catalogo.password);
    const garantias = new GarantiasPage(paginaAdmin);
    await garantias.abrir();
    const garantia = garantias.tarjeta(disfraz.nombre);
    await garantia.getByRole("button", { name: "Devolver garantía · S/ 30.00", exact: true }).click();
    const resuelta = paginaAdmin.waitForResponse(res => res.url().endsWith(`/api/devoluciones/${devolucion.id}/garantia`) && res.request().method() === "POST");
    await garantia.getByRole("button", { name: "Sí, devolver S/ 30.00", exact: true }).click();
    expect((await resuelta).status()).toBe(200);
    const guardada = await catalogo.db.devolucion.findUniqueOrThrow({ where: { id: devolucion.id } });
    expect(guardada.garantiaEstado).toBe("DEVUELTA");
    expect(guardada.garantiaReembolsoId).toMatch(/^re_/);
    const reembolso = await stripe.refunds.retrieve(guardada.garantiaReembolsoId!);
    expect(reembolso.amount).toBe(3000);
    expect(reembolso.currency).toBe("pen");
    expect(reembolso.payment_intent).toBe(paymentIntentId);
    expect(reembolso.charge).toBe(chargeId);
    await expect.poll(async () => (await stripe.refunds.retrieve(reembolso.id)).status, { timeout: 30_000 }).toBe("succeeded");
    const cargoFinal = await stripe.charges.retrieve(chargeId);
    expect(cargoFinal.amount_refunded).toBe(3000);
    expect(cargoFinal.payment_method).toBe(cargo.payment_method);
    await page.goto("http://localhost:5173/mis-alquileres");
    await page.getByRole("tab", { name: /^Historial/ }).click();
    const comprobante = new MisAlquileresPage(page).tarjeta("Alquiler").locator(".garantia");
    await expect(comprobante).toContainText(reembolso.id);
    evidencia.estado = "APROBADO_STRIPE_REAL_TEST";
    evidencia.etapa = "reembolso_verificado";
    evidencia.devolucionId = devolucion.id;
    evidencia.refundId = reembolso.id;
    evidencia.reembolsoCentavos = 3000;
    evidencia.refundStatus = "succeeded";
    evidencia.mismaTransaccionYMetodo = true;
    evidencia.tarjetaUltimos4 = "4242";
    if (consumidor) {
      const finAplicacion = Date.now();
      evidencia.duracionAplicacionMs = finAplicacion - inicioAplicacion;
      const independiente = await consumidor.detener();
      evidencia.consumidor = independiente;
      expect(independiente.codigo).toBe(0);
      expect(independiente.error).toBeUndefined();
      expect(independiente.cancelado).toBe(true);
      expect(independiente.intentId).not.toBe(paymentIntentId);
      const solapadas = independiente.operaciones?.filter(op => op.nombre === 'consultar' && op.inicio >= inicioAplicacion && op.fin <= finAplicacion) ?? [];
      expect(solapadas.length, 'Lecturas del otro consumidor durante el flujo de la aplicación').toBeGreaterThanOrEqual(2);
      const externo = await stripe.paymentIntents.retrieve(independiente.intentId!);
      expect(externo).toMatchObject({ amount: 700, currency: 'pen', status: 'canceled', livemode: false });
      expect(externo.metadata.runId).toBe(independiente.runId);
      expect(await catalogo.db.alquiler.count({ where: { usuarioId: catalogo.usuarioId } })).toBe(1);
      expect((await stripe.charges.retrieve(chargeId)).amount_refunded).toBe(3000);
      evidencia.consultasSolapadas = solapadas.length;
      evidencia.mismaCuenta = true;
      evidencia.sinInterferenciaFuncional = true;
      evidencia.rendimiento = 'Tiempos descriptivos; sin referencia ni umbral de degradación';
      evidencia.estado = 'APROBADO_COEXISTENCIA_FUNCIONAL_STRIPE_TEST';
    }
  } finally {
    if (consumidor) evidencia.consumidor = await consumidor.detener();
    if (evidencia.estado !== (coexistencia ? "APROBADO_COEXISTENCIA_FUNCIONAL_STRIPE_TEST" : "APROBADO_STRIPE_REAL_TEST")) evidencia.estado = "INCOMPLETO_NO_ACREDITADO";
    writeFileSync(new URL("resultado.json", directorio), JSON.stringify(evidencia, null, 2) + "\n");
    await contextoAdmin.close();
    if (adminId) {
      await catalogo.db.devolucion.updateMany({ where: { garantiaResueltaPorId: adminId }, data: { garantiaResueltaPorId: null } });
      await catalogo.db.sesionActiva.deleteMany({ where: { usuarioId: adminId } });
      await catalogo.db.usuario.delete({ where: { id: adminId } });
    }
    if (sesionId) {
      const sesion = await stripe.checkout.sessions.retrieve(sesionId);
      if (sesion.status === "open") await stripe.checkout.sessions.expire(sesionId);
    }
  }
});
